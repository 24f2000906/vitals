import type { jsPDF } from "jspdf";
import type { Finding, ProfileData, Reading } from "./profile";
import { dateSpan, statusLabel, summarySentence } from "./profile";
import { LEVEL_LABEL } from "./metrics";
import type { HistoryEntry } from "./types";
import { formatDate } from "./utils";

export interface PdfInput {
  profile: ProfileData;
  history: HistoryEntry[];
  readings: Reading[];
  findings: Finding[];
  documentCount: number;
  aiSummary?: string;
}

type RGB = [number, number, number];
const INK: RGB = [28, 38, 29];
const MUTED: RGB = [90, 107, 91];
const FOREST: RGB = [82, 107, 80];
const PALE: RGB = [229, 237, 225];
const IVORY: RGB = [246, 247, 242];
const TONE: Record<string, RGB> = { ok: [47, 133, 90], caution: [183, 121, 31], high: [197, 48, 48] };

const W = 210; // A4 portrait, mm
const M = 14;
const CW = W - 2 * M;
const CONTENT_LIMIT = 277; // footer starts below this
const PT = 0.3528; // mm per point

/** Built-in PDF fonts only cover Latin-1; swap curly quotes and replace anything else so nothing prints garbled. */
const clean = (t: string) =>
  t
    .replace(/[\u2018\u2019]/g, "'")
    .replace(/[\u201C\u201D]/g, '"')
    .replace(/[\u2013\u2014]/g, "-")
    .replace(/[^\u0000-\u00FF]/g, "?");

const DISCLAIMER =
  "Generated by VITALS from information entered by the account holder and values read from uploaded reports. It summarises records only: it is not a diagnosis and does not replace advice from a doctor.";

/**
 * Draws (or only measures, when draw=false) the whole page and returns the y position where content ends.
 * The caller tries layouts from roomiest to tightest until the content fits on one page.
 */
function render(doc: jsPDF, d: PdfInput, generatedAt: string, scale: number, maxItems: number, draw: boolean, qrImage?: string | null): number {
  const lh = (pt: number) => pt * scale * PT * 1.3;
  const font = (pt: number, bold = false, color: RGB = INK) => {
    doc.setFont("helvetica", bold ? "bold" : "normal");
    doc.setFontSize(pt * scale);
    doc.setTextColor(...color);
  };
  const txt = (t: string, x: number, y: number, align: "left" | "right" = "left") => {
    if (draw) doc.text(clean(t), x, y, { align });
  };
  const clip = (t: string, width: number) => {
    const lines = doc.splitTextToSize(clean(t), width) as string[];
    return lines.length > 1 ? lines[0].slice(0, -3).trimEnd() + "..." : clean(t);
  };

  // Header band: fixed size so "Vitals" always sits at the top
  if (draw) {
    doc.setFillColor(...FOREST);
    doc.rect(0, 0, W, 28, "F");
    doc.setFont("helvetica", "bold");
    doc.setFontSize(28);
    doc.setTextColor(255, 255, 255);
    doc.text("Vitals", M, 18.5);

    const rightMargin = qrImage ? W - M - 26 : W - M;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.text("Health profile summary", rightMargin, 13.5, { align: "right" });
    doc.text(clean(generatedAt), rightMargin, 19.5, { align: "right" });

    if (qrImage) {
      // High-contrast white card for the permanent QR pass
      doc.setFillColor(255, 255, 255);
      doc.roundedRect(W - M - 23, 2.5, 23, 23, 1.5, 1.5, "F");
      doc.addImage(qrImage, "PNG", W - M - 22, 3.5, 21, 21);
    }
  }
  let y = 28 + 6;

  // Identity
  const p = d.profile;
  font(17, true);
  y += lh(17);
  txt(clip(p.name, CW), M, y);
  font(9.5, false, MUTED);
  y += lh(9.5) + 0.6;
  txt([p.relationship, p.age, p.gender].filter(Boolean).join("  |  "), M, y);
  y += 3;

  const cells: [string, string | null][] = [
    ["Date of birth", p.dob ? formatDate(p.dob) : null],
    ["Age", p.age],
    ["Gender", p.gender],
    ["Relationship", p.relationship],
    ["Email", p.email],
    ["Phone", p.phone],
    ["Documents on file", String(d.documentCount)],
    ["Records entered", `${d.history.length} history entries`],
  ];
  const colW = CW / 2;
  const cellH = lh(7.5) + lh(9.5) + 2.2;
  for (let r = 0; r < cells.length; r += 2) {
    for (let c = 0; c < 2; c++) {
      const cell = cells[r + c];
      if (!cell) continue;
      const x = M + c * colW;
      font(7.5, false, MUTED);
      txt(cell[0], x, y + lh(7.5));
      font(9.5, false, cell[1] ? INK : MUTED);
      txt(clip(cell[1] ?? "Not provided", colW - 4), x, y + lh(7.5) + lh(9.5));
    }
    y += cellH;
  }

  const section = (title: string) => {
    y += 3.5;
    font(10.5, true, FOREST);
    y += lh(10.5);
    txt(title, M, y);
    if (draw) {
      doc.setDrawColor(...PALE);
      doc.setLineWidth(0.4);
      doc.line(M, y + 1.4, W - M, y + 1.4);
    }
    y += 3;
  };
  const muted = (t: string) => {
    font(8.5, false, MUTED);
    y += lh(8.5);
    txt(t, M, y);
    y += 0.8;
  };

  // Summary sentence
  section(d.aiSummary ? "AI Medical Summary" : "Summary");
  font(9.5);
  const summaryText = d.aiSummary || summarySentence(d.history);
  const summary = doc.splitTextToSize(clean(summaryText), CW) as string[];
  for (const line of summary) {
    y += lh(9.5);
    txt(line, M, y);
  }

  // Latest readings
  section("Latest readings from reports");
  if (!d.readings.length) {
    muted("No lab values have been read from uploaded reports yet.");
  } else {
    const gap = 3;
    const bw = (CW - gap * 2) / 3;
    const bh = lh(7.5) + lh(12) + lh(7.5) + 4.5;
    d.readings.slice(0, 3).forEach((r, i) => {
      const x = M + i * (bw + gap);
      if (draw) {
        doc.setFillColor(...IVORY);
        doc.setDrawColor(...PALE);
        doc.setLineWidth(0.3);
        doc.roundedRect(x, y, bw, bh, 2, 2, "FD");
      }
      font(7.5, false, MUTED);
      txt(r.label, x + 3, y + 2 + lh(7.5));
      font(12, true);
      txt(clip(r.value, bw - 6), x + 3, y + 2 + lh(7.5) + lh(12));
      font(7.5, true, TONE[r.level]);
      txt(LEVEL_LABEL[r.level], x + 3, y + 2 + lh(7.5) + lh(12) + lh(7.5));
    });
    y += bh + 0.5;
  }

  // History groups
  const group = (title: string, kind: HistoryEntry["kind"], empty: string) => {
    const items = d.history.filter((e) => e.kind === kind);
    section(`${title} (${items.length})`);
    if (!items.length) return muted(empty);
    for (const e of items.slice(0, maxItems)) {
      const meta = [statusLabel(e.kind, e.status), dateSpan(e)].filter(Boolean).join("  |  ");
      font(8, false, MUTED);
      const metaW = doc.getTextWidth(clean(meta)) + 3;
      font(9.5, true);
      y += lh(9.5);
      txt(clip(e.title, CW - metaW), M, y);
      font(8, false, MUTED);
      txt(meta, W - M, y, "right");
      if (e.notes) {
        font(8, false, MUTED);
        y += lh(8);
        txt(clip(e.notes, CW), M, y);
      }
      y += 1.3;
    }
    if (items.length > maxItems) muted(`+${items.length - maxItems} more in VITALS`);
  };
  group("Conditions and diseases", "condition", "None recorded.");
  group("Treatments and medication", "treatment", "None recorded.");
  group("Allergies", "allergy", "None recorded.");

  // Findings from reports
  if (d.findings.length) {
    section("Flagged in reports");
    for (const f of d.findings.slice(0, maxItems)) {
      font(8.5);
      const lines = (doc.splitTextToSize(clean(`${f.label}: ${f.message}`), CW - 5) as string[]).slice(0, 2);
      lines.forEach((line, i) => {
        y += lh(8.5);
        if (i === 0 && draw) {
          doc.setFillColor(...TONE[f.level]);
          doc.circle(M + 1, y - 1, 0.8, "F");
        }
        txt(line, M + 4, y);
      });
      y += 1;
    }
    if (d.findings.length > maxItems) muted(`+${d.findings.length - maxItems} more in VITALS`);
  }

  // Footer
  if (draw) {
    doc.setDrawColor(...PALE);
    doc.setLineWidth(0.4);
    doc.line(M, 281, W - M, 281);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7);
    doc.setTextColor(...MUTED);
    doc.text(doc.splitTextToSize(DISCLAIMER, CW) as string[], M, 285);
  }
  return y;
}

export async function downloadProfilePdf(input: PdfInput) {
  const { jsPDF } = await import("jspdf");
  const doc = new jsPDF({ unit: "mm", format: "a4", orientation: "portrait", compress: true });
  const generatedAt = `Generated ${formatDate(new Date().toISOString().slice(0, 10))}`;

  let qrDataUrl: string | null = null;
  if (input.profile.shareCode) {
    try {
      const QRCode = await import("qrcode");
      const origin = typeof window !== "undefined" ? window.location.origin : "https://vitals.ai";
      const shareUrl = `${origin}/share/${input.profile.shareCode}`;
      qrDataUrl = await QRCode.toDataURL(shareUrl, {
        margin: 1,
        width: 140,
        color: { dark: "#1c261d", light: "#ffffff" },
      });
    } catch {
      /* ignore qr generation failure */
    }
  }

  // Roomiest layout that still fits on one page: shrink type first, then show fewer entries per list.
  let chosen = { scale: 0.7, items: 2 };
  search: for (const items of [8, 6, 5, 4, 3, 2]) {
    for (const scale of [1, 0.95, 0.9, 0.85, 0.8, 0.75, 0.7]) {
      if (render(doc, input, generatedAt, scale, items, false, qrDataUrl) <= CONTENT_LIMIT) {
        chosen = { scale, items };
        break search;
      }
    }
  }
  render(doc, input, generatedAt, chosen.scale, chosen.items, true, qrDataUrl);

  const slug = input.profile.name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "profile";
  doc.setProperties({ title: `Vitals health profile - ${clean(input.profile.name)}`, creator: "VITALS" });
  doc.save(`vitals-${slug}-profile.pdf`);
}