"use client";
import { motion } from "framer-motion";
import { Bot, RefreshCw, Sparkles } from "lucide-react";
import { useEffect, useState } from "react";
import { Button } from "@/components/ui/button";
import { api } from "@/lib/api";

interface Props {
  memberId: number | null;
  onSummaryLoaded?: (summary: string) => void;
}

export function AiSummary({ memberId, onSummaryLoaded }: Props) {
  const [summary, setSummary] = useState<string | null>(null);
  const [source, setSource] = useState<"nvidia" | "fallback" | "none" | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");

  async function load(forceRefresh = false) {
    setLoading(true);
    setError("");
    try {
      const res = await api.profileSummary(memberId, forceRefresh);
      setSummary(res.summary);
      setSource(res.source);
      onSummaryLoaded?.(res.summary ?? "");
    } catch (e) {
      setError(e instanceof Error ? e.message : "Couldn't load AI summary");
    } finally {
      setLoading(false);
    }
  }

  useEffect(() => {
    void load(false);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [memberId]);

  if (!loading && !summary) {
    return null;
  }

  return (
    <motion.section
      aria-labelledby="ai-summary-title"
      initial={{ opacity: 0, y: 16 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ type: "spring", stiffness: 100, damping: 20, delay: 0.1 }}
      className="space-y-4"
    >
      <div className="flex items-center justify-between">
        <h2 id="ai-summary-title" className="flex items-center gap-2 font-display text-2xl font-semibold tracking-tight">
          <Sparkles className="size-5 text-primary" aria-hidden />
          AI Medical Summary
        </h2>
        <Button size="sm" variant="outline" onClick={() => void load(true)} loading={loading}>
          <RefreshCw className="size-4" /> Refresh
        </Button>
      </div>

      <div className="glass rounded-2xl p-5">
        {loading ? (
          <div className="space-y-2">
            <div className="h-4 w-full animate-pulse rounded bg-muted" />
            <div className="h-4 w-4/5 animate-pulse rounded bg-muted" />
            <div className="h-4 w-3/5 animate-pulse rounded bg-muted" />
          </div>
        ) : error ? (
          <p role="alert" className="text-sm text-danger">
            {error}
          </p>
        ) : (
          <>
            <p className="text-sm leading-relaxed text-foreground">{summary}</p>
            <div className="mt-4 flex items-center gap-2 border-t border-border pt-3">
              <Bot className="size-3.5 shrink-0 text-muted-foreground" aria-hidden />
              <p className="text-xs text-muted-foreground">
                {source === "nvidia"
                  ? "Generated by NVIDIA AI from your uploaded medical documents."
                  : "Summary based on your profile data. Upload lab reports for AI-powered insights."}
              </p>
            </div>
          </>
        )}
      </div>
    </motion.section>
  );
}
